import { FieldItem } from './../../models/common/field-item';
import { NavigationLink } from './../../models/common/navigation-link';
import { TabItem } from 'src/app/models/common/tab-items';
import { PolicyService } from './../services/policy.service';
import { BaseComponent } from 'src/app/system-common/base/base.component';
import { Component, OnChanges, SimpleChanges, Input, ChangeDetectionStrategy } from '@angular/core';

@Component({
  selector: '',
  template: '',
  changeDetection: ChangeDetectionStrategy.Eager,
  standalone: false,
})
export class PolicyDocumentHandlerComponent extends BaseComponent<PolicyService> implements OnChanges {
  public partyDocumentTabList: TabItem[];
  public selectedPartyDocumentTab: TabItem;
  public navigationLinkList: NavigationLink[];
  public uwPartyGuidList: string[];
  public uwDocumentCategoryList: string[];
  public isAutoUwGeneratedFl: boolean;
  public isSelectedCheckBoxReq: boolean;
  responseUpdated: boolean;

  constructor(policyService: PolicyService) {
    super(policyService);
    this.loadPartyDocumentTab();
    this.isSelectedCheckBoxReq = true;
    // console.log(this.service.responseIO);
  }
  ngOnInit() {
    if (this.isAutoUwGeneratedFl == undefined) this.isAutoUwGeneratedFl = false;
    this.setNavigationLinks();
    this.setDocumentProperty();
  }
  ngOnChanges(changes: SimpleChanges) {
    this.setDocumentProperty();
  }

  private setNavigationLinks() {
    this.navigationLinkList = [];
    this.service.responseIO.data['PartyDocumentList'][
      this.selectedPartyDocumentTab.index
    ].DocumentCategoryList.filter((documentCategory) => {
      if (this.checkApplicableDocCategoryCd(documentCategory.docCategoryCd)) {
        let nav = new NavigationLink();
        nav.link = documentCategory.docCategoryCd;
        let navLabel = '';
        if (this.service.getFieldMetadata(documentCategory, 'docCategoryCd') == undefined) {
          if (documentCategory.DocumentList.length > 0)
            navLabel = this.service.getFieldLookupDesc(documentCategory.DocumentList[0], 'docCategoryCd');
        } else {
          navLabel = this.service.getFieldLookupDesc(documentCategory, 'docCategoryCd');
        }
        nav.labelKey = navLabel;
        // nav.labelKey = this.service.getFieldLookupDesc(documentCategory, 'docCategoryCd');
        this.navigationLinkList.push(nav);
      }
    });
  }

  public setSelectedTab(tab: TabItem) {
    this.selectedPartyDocumentTab = tab;
    this.setNavigationLinks();
  }

  protected loadUWDocuments() {
    this.uwPartyGuidList = [];
    this.uwDocumentCategoryList = [];
    for (let i = 0; i < this.service.responseIO.data.PartyDocumentList.length; i++) {
      this.service.responseIO.data['PartyDocumentList'][i].DocumentCategoryList.forEach((documentCategory) => {
        documentCategory.DocumentList.forEach((document) => {
          document['isEnabled'] =
            this.service.getFieldMetadataPropertyValue(document, 'documentCd', 'ENABLED') == 'NO' ? false : true;
          if (document.isAutoGeneratedFl == 'YES_UW') {
            this.uwPartyGuidList.push(document.partyGuid);
            this.uwDocumentCategoryList.push(document.docCategoryCd);
          }
        });
      });
    }
  }
  protected loadPartyDocumentTab() {
    if (
      this.service.responseIO.data.PartyDocumentList != undefined &&
      this.service.responseIO.data.PartyDocumentList.length != 0
    ) {
      this.loadUWDocuments();
      this.partyDocumentTabList = [];
      let tabIndex = 0;
      let userReferenceId =
        this.service.getUserLoginData() != undefined
          ? this.service.getUserLoginData()['userReferenceId']
          : undefined;
      this.service.responseIO.data.PartyDocumentList.filter((documentParty) => {
        let tab = new TabItem();
        tab.text =
          documentParty.partyRole === undefined
            ? documentParty.partyName
            : documentParty.partyRole === null
            ? documentParty.partyName
            : documentParty.partyRole === ''
            ? documentParty.partyName
            : documentParty.partyRole + ': ' + documentParty.partyName;
        tab.isSelected = false;
        tab.id = documentParty.partyGuid;
        tab.index = tabIndex;
        if (
          userReferenceId != undefined &&
          documentParty.partyGuid != userReferenceId &&
          this.service.responseIO.data.Entity.allowModifyAllRoles != 'YES'
        )
          tab.visible = false;
        this.partyDocumentTabList.push(tab);
        tabIndex++;
      });

      this.partyDocumentTabList[0].isSelected = true;
      //this.selectedPartyDocumentTab = new TabItem();
      this.selectedPartyDocumentTab = this.partyDocumentTabList[0];
    }
  }
  /**
   * Calling this function seperately since only label is visible on screen and user tends to click on the Label rather
   * than the checkbox
   */
  public byPassOCrLabelClick(documentObj) {
    if (this.service.responseIO.data.Entity.statusCd != 'PENDING') return;
    if (documentObj.disableOcrFl == undefined) documentObj.disableOcrFl = 'YES';
    else if (documentObj.disableOcrFl == 'YES') documentObj.disableOcrFl = 'NO';
    else if (documentObj.disableOcrFl == 'NO') documentObj.disableOcrFl = 'YES';
    this.disableOcrFl_change(undefined, documentObj);
  }

  protected disableOcrFl_change(item: FieldItem, model?) {
    if (this.service.responseIO.data.Entity.statusCd != 'PENDING') return;
    if (item != undefined) model = item.model;
    if (model.disableOcrFl == 'YES' && model.DocumentImageList.length > 0) {
      this.confirm(
        this.service.getMultilingualLabel('ocrConfirmation'),
        () => {
          model.DocumentImageList = [];
        },
        () => {
          model.disableOcrFl = 'NO';
        }
      );
    }
  }

  public checkApplicableDocCategoryCd(currDocCategoryCd: string): boolean {
    let isApplicableDocCategoryCd: boolean = false;
    if (
      this.uwDocumentCategoryList.length == 0 ||
      (this.uwDocumentCategoryList.length > 0 &&
        !this.isAutoUwGeneratedFl &&
        !this.uwDocumentCategoryList.includes(currDocCategoryCd)) ||
      (this.uwDocumentCategoryList.length > 0 &&
        this.isAutoUwGeneratedFl &&
        this.uwDocumentCategoryList.includes(currDocCategoryCd))
    )
      isApplicableDocCategoryCd = true;
    return isApplicableDocCategoryCd;
  }

  /*****
   * AIML related code starts here
   */
  verifyDocumentList: any;
  isVerifiedButtonClicked: boolean;
  onVerifyClick(documentObject: any) {
    // console.log(documentObjects);
    this.verifyDocumentList = undefined;
    this.verifyDocumentList = documentObject.DocumentImageList;
    this.isVerifiedButtonClicked = true;
  }

  onImageVerificationDone(val) {
    this.isVerifiedButtonClicked = false;
    this.verifyDocumentList = undefined;
  }

  /*****
   * AIML related code ends here
   */

  protected setDocumentProperty() {
    let docCounter = 0;
    for (let i = 0; i < this.service?.responseIO?.data?.PartyDocumentList?.length; i++) {
      this.service.responseIO.data['PartyDocumentList'][i].DocumentCategoryList.forEach((documentCategory) => {
        documentCategory.DocumentList.forEach((document) => {
          document['objName'] =
            this.service?.responseIO?.data?.PartyDocumentList[0]?.DocumentCategoryList[0]?.DocumentList[0]?.objName;
          document['imageObjName'] =
            this.service?.responseIO?.data?.PartyDocumentList[0]?.DocumentCategoryList[0]?.DocumentList[0]
              ?.DocumentImageList[0]?.objName || 'DocumentImageList';
          document['rowIndex'] = docCounter++;
          document['isEnabled'] =
            this.service.getFieldMetadataPropertyValue(document, 'documentCd', 'ENABLED') == 'NO' ? false : true;
          document['allowMultiImageUplodFl'] =
            this.service.getFieldMetadataPropertyValue(document, 'documentCd', 'ALLOWMULTIIMAGEUPLOADFL') == 'NO'
              ? false
              : true;
          document = this.service.getFieldMetadata(document, 'docCategoryCd');
        });
      });
    }
  }
}
